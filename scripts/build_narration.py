"""Synthesise the guided-tour narration (scripts/narration_script.py) with Kokoro (local, Apache-2.0 model) and
write, for Godot:
  godot/assets/narration/<chapter>_<beat>.ogg      one clip per tour beat (24 kHz mono Ogg Vorbis)
  godot/data/narration/narration.json              per beat: file, duration, sentence timings, cue timings
and, for reviewers, docs/NARRATION_SCRIPT.md (the full text with durations).

Each sentence is synthesised separately and the clips are joined with a short pause, so sentence start/end times
are exact (they drive the subtitles).  A cue's time is the start of its sentence plus the phrase's character
offset as a fraction of the sentence duration (within ~0.3 s of the spoken word; good enough for a 5 s pulse).

  .venv/Scripts/python.exe scripts/build_narration.py [--voice af_heart] [--speed 0.95] [--only chapter_id]
Model files (not in the repo): tools/kokoro/kokoro-v1.0.onnx and voices-v1.0.bin from
https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
"""
import argparse
import json
import os
import re
import sys
import time

import numpy as np
import soundfile as sf

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import narration_script as NS  # noqa: E402

MODEL = os.path.join(ROOT, "tools", "kokoro", "kokoro-v1.0.onnx")
VOICES = os.path.join(ROOT, "tools", "kokoro", "voices-v1.0.bin")
OUT_AUDIO = os.path.join(ROOT, "godot", "assets", "narration")
OUT_JSON = os.path.join(ROOT, "godot", "data", "narration", "narration.json")
OUT_MD = os.path.join(ROOT, "docs", "NARRATION_SCRIPT.md")
PAUSE_S = 0.38          # silence between sentences
TAIL_S = 0.6            # silence at the end of a clip
CHAPTER_ORDER = ["basement", "feltville", "eruption", "precipitation", "burial", "erosion", "present", "worm"]
CHAPTER_TITLES = {
    "basement": "1. Proterozoic basement and rift fluids", "feltville": "2. Feltville Formation deposition",
    "eruption": "3. Preakness eruption", "precipitation": "4. Carnelian precipitation",
    "burial": "5. Flow-top exposure, second flow and burial", "erosion": "6. Tilting, uplift and erosion",
    "present": "7. Glaciation and the present day", "worm": "W. Worm's-eye view",
}


def split_sentences(text):
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z\"'(])", text.strip())
    return [p.strip() for p in parts if p.strip()]


def write_ogg(path, clip, sr):
    """Blockwise write: libsndfile's Vorbis encoder overflows the stack when handed a 20 s clip in one call."""
    with sf.SoundFile(path, "w", samplerate=sr, channels=1, format="OGG", subtype="VORBIS") as f:
        for i in range(0, clip.size, 8192):
            f.write(clip[i:i + 8192])


def phonemize_fixed(tok, sentence):
    """Phonemise a sentence, then swap in the IPA fixes for the words espeak gets wrong."""
    ph = tok.phonemize(sentence, lang="en-us")
    for word, ipa in NS.PHONEME_FIXES.items():
        if re.search(r"\b" + re.escape(word) + r"\b", sentence, flags=re.IGNORECASE):
            wp = tok.phonemize(word, lang="en-us").strip()
            if wp in ph:
                ph = ph.replace(wp, ipa)
            else:
                print("    note: fix for %r not applied (phonemes not found verbatim)" % word)
    return ph


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default=NS.VOICE)
    ap.add_argument("--speed", type=float, default=NS.SPEED)
    ap.add_argument("--only", default="")
    args = ap.parse_args()
    for p in (MODEL, VOICES):
        if not os.path.exists(p):
            sys.exit("missing %s (see the docstring)" % p)
    from kokoro_onnx import Kokoro
    from kokoro_onnx.tokenizer import Tokenizer
    tok = Tokenizer()
    kk = Kokoro(MODEL, VOICES)
    os.makedirs(OUT_AUDIO, exist_ok=True)
    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    out = {"voice": args.voice, "speed": args.speed, "engine": "kokoro-onnx (Kokoro-82M v1.0, Apache-2.0)",
           "sample_rate": 24000, "pause_s": PAUSE_S, "tail_s": TAIL_S, "chapters": {}}
    md = ["# Guided-tour narration script\n",
          "Generated by `scripts/build_narration.py` from `scripts/narration_script.py` (voice %s, speed %.2f). "
          "The tour's pacing is set by these clips: each beat of a chapter is shown for the length of its "
          "narration, and the named entities pulse when first mentioned. Durations are of the generated audio.\n"
          % (args.voice, args.speed)]
    total = 0.0
    t_start = time.time()
    for cid in CHAPTER_ORDER:
        beats = NS.SCRIPT[cid]
        if args.only and cid != args.only:
            # keep the previous JSON entry for chapters we are not regenerating
            if os.path.exists(OUT_JSON):
                prev = json.load(open(OUT_JSON, encoding="utf-8"))
                if cid in prev.get("chapters", {}):
                    out["chapters"][cid] = prev["chapters"][cid]
                    total += sum(b["duration"] for b in prev["chapters"][cid]["beats"])
            continue
        md.append("\n## %s\n" % CHAPTER_TITLES[cid])
        cb = []
        for bi, beat in enumerate(beats):
            text = beat["text"]
            sentences = split_sentences(text)
            audio = []
            sent_times = []
            t = 0.0
            for s in sentences:
                ph = phonemize_fixed(tok, s)
                samples, sr = kk.create(ph, voice=args.voice, speed=args.speed, lang="en-us", is_phonemes=True)
                assert sr == 24000
                # trim leading/trailing near-silence so pauses are controlled here, not by the model
                a = np.asarray(samples, dtype=np.float32)
                nz = np.where(np.abs(a) > 0.004)[0]
                if nz.size:
                    a = a[max(0, nz[0] - int(0.04 * sr)): min(a.size, nz[-1] + int(0.12 * sr))]
                dur = a.size / sr
                sent_times.append({"start": round(t, 3), "end": round(t + dur, 3), "text": s})
                audio.append(a)
                audio.append(np.zeros(int(PAUSE_S * sr), dtype=np.float32))
                t += dur + PAUSE_S
            audio[-1] = np.zeros(int(TAIL_S * sr), dtype=np.float32)
            t = t - PAUSE_S + TAIL_S
            clip = np.concatenate(audio)
            peak = float(np.abs(clip).max()) or 1.0
            clip = clip * min(1.0, 0.89 / peak)
            fname = "%s_%d.ogg" % (cid, bi + 1)
            write_ogg(os.path.join(OUT_AUDIO, fname), clip, sr)
            # cues: phrase -> time
            cues = []
            low = text.lower()
            for phrase, target in beat["cues"]:
                idx = low.find(phrase.lower())
                if idx < 0:
                    sys.exit("cue phrase %r not in %s beat %d text" % (phrase, cid, bi + 1))
                # which sentence, and where in it
                pos = 0
                when = None
                for st in sent_times:
                    s = st["text"]
                    sidx = low.find(s.lower(), pos)
                    pos = sidx + len(s)
                    if sidx <= idx < sidx + len(s):
                        frac = (idx - sidx) / max(len(s), 1)
                        when = st["start"] + frac * (st["end"] - st["start"])
                        break
                if when is None:
                    sys.exit("cue phrase %r in %s beat %d spans sentences" % (phrase, cid, bi + 1))
                c = {"t": round(max(0.0, when - 0.15), 3), "phrase": phrase}
                c.update(target)
                cues.append(c)
            cues.sort(key=lambda c: c["t"])
            cb.append({"file": "res://assets/narration/" + fname, "duration": round(t, 3), "sentences": sent_times,
                       "cues": cues, "text": text})
            total += t
            md.append("**Beat %d** (%.1f s): %s\n" % (bi + 1, t, text))
            if cues:
                md.append("  *cues:* " + "; ".join("%.1f s %s" % (c["t"], c["phrase"]) for c in cues) + "\n")
            print("  %s beat %d: %.1f s, %d sentences, %d cues" % (cid, bi + 1, t, len(sentences), len(cues)))
        out["chapters"][cid] = {"beats": cb}
    out["total_s"] = round(total, 1)
    json.dump(out, open(OUT_JSON, "w", encoding="utf-8"), indent=1)
    md.insert(2, "\nTotal narration: %d min %02d s over %d beats.\n" % (total // 60, total % 60, sum(len(v["beats"]) for v in out["chapters"].values())))
    open(OUT_MD, "w", encoding="utf-8").write("\n".join(md))
    print("wrote %s (%.1f min of narration) in %.0f s" % (OUT_JSON, total / 60.0, time.time() - t_start))


if __name__ == "__main__":
    main()
